export function photoUrl(id: string, width = 800): string {
  return `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&q=70&w=${width}`;
}

function photos(
  listingId: string,
  street: string,
  ids: { exterior: string; living: string; bedroom: string; kitchen: string; bath: string; extra?: string },
): ListingPhoto[] {
  const set: [string, string][] = [
    ['Exterior', ids.exterior],
    ['Living room', ids.living],
    ['Bedroom', ids.bedroom],
    ['Kitchen', ids.kitchen],
    ['Bathroom', ids.bath],
  ];
  if (ids.extra) set.push(['Dining area', ids.extra]);
  return set.map(([room, id], i) => ({
    id: `${listingId}-p${i}`,
    url: id,
    room,
    alt: `${room}, ${street} (illustrative stock photo)`,
  }));
}

/** Tenant photos pair with listing photos of the same room for the before/after slider. */
function tenantPhotos(listingId: string, list: ListingPhoto[], dates: string[]): TenantPhoto[] {
  const living = list[1];
  const bedroom = list[2];
  const kitchen = list[3];
  const bath = list[4];
  return [
    { id: `${listingId}-t0`, url: living.url, room: 'Living room', angle: 'From the entry door', date: dates[0], pairsWith: living.id },
    { id: `${listingId}-t1`, url: bedroom.url, room: 'Bedroom', angle: 'From the window wall', date: dates[0], pairsWith: bedroom.id },
    { id: `${listingId}-t2`, url: kitchen.url, room: 'Kitchen', angle: 'Counter, facing the sink', date: dates[1], pairsWith: kitchen.id },
    { id: `${listingId}-t3`, url: bath.url, room: 'Bathroom', angle: 'From the doorway', date: dates[1], pairsWith: bath.id },
    { id: `${listingId}-t4`, url: P.empty, room: 'Second bedroom, unfurnished', angle: 'Corner, wide angle', date: dates[1] },
  ];
}

function build(
  l: Omit<Listing, 'photos' | 'tenantPhotos'> & {
    photoIds: Parameters<typeof photos>[2];
    tenantDates: [string, string];
  },
): Listing {
  const { photoIds, tenantDates, ...rest } = l;
  const list = photos(l.id, l.street, photoIds);
  return { ...rest, photos: list, tenantPhotos: tenantPhotos(l.id, list, tenantDates) };
}

